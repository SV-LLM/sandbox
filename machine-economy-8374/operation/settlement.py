#!/usr/bin/env python3
"""Settlement submission leg -- Gate 2 (2026-11-17).

Closes the settlement boundary left by BUILD-Q-18: the endpoint
verified x402 "exact"-scheme EIP-3009 authorizations cryptographically
but never broadcast them, so verified fees never moved on-chain.

Design: an EIP-3009 transferWithAuthorization can be submitted by ANY
party; the submitter pays the gas. This module is that submitter. A
dedicated gas-only relayer key lives on this node (settlement_relayer
.json, mode 0600, generated by relayer_setup.py). The relayer holds no
USDC and no ecosystem material by design -- it pays Base gas only, so
its compromise surface is the dust ETH balance and nothing else.

attempt_settlement() is called once per verified authorization. Its
outcome NEVER changes the crossing's disposition: under the active
pricing mode (a) the fee follows the evaluation (ALLOW, DENY, and
FAIL_CLOSED each bear the fee for the unit of compute consumed), the
receipt pair is written regardless, and the settlement record rides
the pair. A settlement FAIL_CLOSED therefore means: the fee was
earned under mode (a) and verified, but not yet collected on-chain;
the authorization remains submittable later (a reverted or unsent
submission does not consume the EIP-3009 nonce on-chain).

Failure codes (SETTLEMENT_* -- distinct from the PAYMENT_* codes of
BUILD-Q-18, which are verification failures and never reach here):
  SETTLEMENT_RELAYER_KEY_MISSING  relayer key file absent/unreadable
  SETTLEMENT_RELAYER_UNFUNDED    relayer balance cannot cover gas
  SETTLEMENT_RPC_UNREACHABLE     every configured RPC failed
  SETTLEMENT_SIMULATION_REVERTED eth_estimateGas reverted the call
  SETTLEMENT_BROADCAST_FAILED    eth_sendRawTransaction errored
  SETTLEMENT_REVERTED_ONCHAIN    tx mined with status 0
Statuses: SETTLED (mined, status 1), SUBMITTED (broadcast accepted,
confirmation still pending when the record was written), FAIL_CLOSED
(one of the codes above), DISABLED (config flag off), NOT_ATTEMPTED.

Stdlib only, matching the endpoint's build discipline.
"""
import hashlib, hmac, json, os, time
import urllib.error, urllib.request
from keccak_pure import keccak256, eip55

P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)
CHAIN_ID = 8453
OWNING_GOAL = "MACHINE-ECONOMY-ENTRY-01 / GATE-2"
TRANSFER_SELECTOR = keccak256(
    b"transferWithAuthorization(address,address,uint256,uint256,"
    b"uint256,bytes32,uint8,bytes32,bytes32)")[:4]


def _ec_add(p, q):
    if p is None: return q
    if q is None: return p
    if p[0] == q[0] and (p[1] + q[1]) % P == 0: return None
    if p == q:
        m = (3 * p[0] * p[0]) * pow(2 * p[1], -1, P) % P
    else:
        m = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (m * m - p[0] - q[0]) % P
    return (x, (m * (p[0] - x) - p[1]) % P)


def _ec_mul(k, p):
    r = None
    while k:
        if k & 1: r = _ec_add(r, p)
        p = _ec_add(p, p)
        k >>= 1
    return r


def address_from_private(priv):
    q = _ec_mul(priv, G)
    unc = q[0].to_bytes(32, "big") + q[1].to_bytes(32, "big")
    return eip55(keccak256(unc)[-20:].hex())


def _rfc6979_k(priv, digest_bytes):
    bx = priv.to_bytes(32, "big")
    bh = (int.from_bytes(digest_bytes, "big") % N).to_bytes(32, "big")
    v = b"\x01" * 32
    k = b"\x00" * 32
    k = hmac.new(k, v + b"\x00" + bx + bh, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    k = hmac.new(k, v + b"\x01" + bx + bh, hashlib.sha256).digest()
    v = hmac.new(k, v, hashlib.sha256).digest()
    while True:
        v = hmac.new(k, v, hashlib.sha256).digest()
        cand = int.from_bytes(v, "big")
        if 1 <= cand < N:
            return cand
        k = hmac.new(k, v + b"\x00", hashlib.sha256).digest()
        v = hmac.new(k, v, hashlib.sha256).digest()


def sign_digest(priv, digest_bytes):
    """Deterministic (RFC 6979) ECDSA over a 32-byte digest, low-s.
    Returns (r, s, recid)."""
    z = int.from_bytes(digest_bytes, "big")
    k = _rfc6979_k(priv, digest_bytes)
    kg = _ec_mul(k, G)
    r = kg[0] % N
    s = (pow(k, -1, N) * (z + r * priv)) % N
    recid = (kg[1] & 1) | (2 if kg[0] >= N else 0)
    if s > N // 2:
        s = N - s
        recid ^= 1
    return r, s, recid


def _rlp_len(length, offset):
    if length < 56:
        return bytes([offset + length])
    lb = length.to_bytes((length.bit_length() + 7) // 8, "big")
    return bytes([offset + 55 + len(lb)]) + lb


def rlp_encode(item):
    if isinstance(item, int):
        if item == 0:
            return rlp_encode(b"")
        return rlp_encode(item.to_bytes((item.bit_length() + 7) // 8, "big"))
    if isinstance(item, (bytes, bytearray)):
        b = bytes(item)
        if len(b) == 1 and b[0] < 0x80:
            return b
        return _rlp_len(len(b), 0x80) + b
    payload = b"".join(rlp_encode(x) for x in item)
    return _rlp_len(len(payload), 0xc0) + payload


def _u256(n):
    return int(n).to_bytes(32, "big")


def _addr_word(a):
    return b"\x00" * 12 + bytes.fromhex(a[2:] if a.startswith("0x") else a)


def parse_signature(sig_hex):
    """Returns (v_normalized_27_28, r_bytes, s_bytes) or raises ValueError."""
    h = sig_hex[2:] if sig_hex.startswith("0x") else sig_hex
    sig = bytes.fromhex(h)
    if len(sig) != 65:
        raise ValueError("signature is not 65 bytes")
    v = sig[64]
    if v in (0, 1):
        v += 27
    if v not in (27, 28):
        raise ValueError("signature v is not 27/28 (or 0/1)")
    return v, sig[0:32], sig[32:64]


def build_transfer_calldata(payment):
    """transferWithAuthorization calldata for a verified payment evidence
    dict (which carries the payer signature under 'signature')."""
    v, r, s = parse_signature(payment["signature"])
    nonce = payment["nonce"]
    nonce = nonce[2:] if nonce.startswith("0x") else nonce
    nonce_b = bytes.fromhex(nonce)
    if len(nonce_b) != 32:
        raise ValueError("nonce is not 32 bytes")
    return TRANSFER_SELECTOR \
        + _addr_word(payment["from"]) + _addr_word(payment["to"]) \
        + _u256(payment["value_micro_usdc"]) \
        + _u256(payment["valid_after"]) + _u256(payment["valid_before"]) \
        + nonce_b + _u256(v) + r + s


class RpcError(Exception):
    pass


def _proxy_candidates():
    """Egress CONNECT proxy candidates for this node, discovered at
    call time and never stored (the tunnel supervisor's pattern):
    this process's env, then a /proc scan for a live process carrying
    the proxy env, then the bare proxy address. All egress on this
    node transits the hatch egress proxy -- direct egress is
    intercepted (TLS WRONG_VERSION_NUMBER, the PAIR-000016 settlement
    failure) -- and the credentialed form rotates with the runtime,
    so it is read fresh here and never copied into a file. The bare
    proxy refuses some hosts (403) but carries others
    (base-rpc.publicnode.com answers through it), so candidates are
    tried in order per RPC URL."""
    out = []
    for k in ("https_proxy", "HTTPS_PROXY", "http_proxy", "HTTP_PROXY"):
        v = os.environ.get(k)
        if v and "hatch-egress-proxy" in v:
            out.append(v)
    try:
        for pid in os.listdir("/proc"):
            if not pid.isdigit():
                continue
            try:
                with open(f"/proc/{pid}/environ", "rb") as f:
                    env = f.read().decode(errors="replace")
                for kv in env.split("\0"):
                    key, _, val = kv.partition("=")
                    if key in ("https_proxy", "HTTPS_PROXY") \
                            and "hatch-egress-proxy" in val:
                        out.append(val)
            except OSError:
                continue
    except OSError:
        pass
    out.append("http://hatch-egress-proxy:3128")
    seen, res = set(), []
    for v in out:
        if v not in seen:
            seen.add(v)
            res.append(v)
    return res


def _proxy_label(proxy):
    """Non-secret label for a proxy candidate (error records are
    receipted on the chain; a credentialed proxy URL must never be
    written into one)."""
    if proxy is None:
        return "direct"
    return "credentialed proxy" if "@" in proxy else "bare proxy"


class Rpc:
    """Minimal JSON-RPC client over the configured public RPCs, in
    order; a transport failure or error response falls through to the
    next URL for idempotent reads only when the caller allows it.
    Every request transits the node's egress CONNECT proxy (see
    _proxy_candidates): for each URL, each discovered proxy is tried
    in order, then a direct attempt as the final fallback. A JSON-RPC
    error response raises immediately (no failover); an HTTP error
    without a JSON-RPC error body counts as transport failure for
    that (URL, proxy) combination. Proxy failover within one URL
    re-sends the identical payload, so it is safe even for
    eth_sendRawTransaction: the same signed bytes hash to the same
    transaction."""

    def __init__(self, urls, timeout=15):
        self.urls = [u for u in urls if u]
        self.timeout = timeout
        self.answered_by = None

    def call(self, method, params, allow_failover=True):
        errors = []
        urls = self.urls if allow_failover else self.urls[:1]
        body = json.dumps({"jsonrpc": "2.0", "id": 1,
                           "method": method, "params": params}).encode()
        openers = [(p, urllib.request.build_opener(
            urllib.request.ProxyHandler({"http": p, "https": p})))
            for p in _proxy_candidates()]
        openers.append((None, urllib.request.build_opener()))
        for url in urls:
            for proxy, opener in openers:
                label = _proxy_label(proxy)
                out = None
                try:
                    req = urllib.request.Request(
                        url, data=body,
                        headers={"Content-Type": "application/json"})
                    with opener.open(req, timeout=self.timeout) as r:
                        out = json.load(r)
                except urllib.error.HTTPError as e:
                    try:
                        parsed = json.loads(e.read())
                    except Exception:
                        parsed = None
                    if isinstance(parsed, dict) and "error" in parsed:
                        out = parsed
                    else:
                        errors.append(
                            f"{url} via {label}: HTTP {e.code}"[:200])
                        continue
                except Exception as e:
                    msg = str(e)
                    if proxy:
                        msg = msg.replace(proxy, label)
                    errors.append(
                        f"{url} via {label}: {type(e).__name__}: {msg}"[:200])
                    continue
                if not isinstance(out, dict) \
                        or ("error" not in out and "result" not in out):
                    errors.append(
                        f"{url} via {label}: malformed response"[:200])
                    continue
                if "error" in out:
                    err = out["error"]
                    msg = err.get("message", str(err)) \
                        if isinstance(err, dict) else str(err)
                    raise RpcError(f"{method}: {msg}"[:300])
                self.answered_by = url
                return out["result"]
        raise RpcError("all RPCs failed: " + " | ".join(errors))


def _key_path(cfg, base_dir):
    kf = cfg.get("relayer_key_file", "settlement_relayer.json")
    return kf if os.path.isabs(kf) else os.path.join(base_dir, kf)


def load_relayer(cfg, base_dir):
    """Returns (priv_int, address). Raises FileNotFoundError/ValueError."""
    with open(_key_path(cfg, base_dir)) as f:
        doc = json.load(f)
    priv = int(doc["private_key"], 16)
    if not (1 <= priv < N):
        raise ValueError("relayer private key out of range")
    return priv, address_from_private(priv)


def public_state(cfg, base_dir):
    """Non-secret settlement state for /health: mode, flag, relayer
    address (public), key presence. Never key material."""
    state = {"mode": cfg.get("mode", "self-relayer"),
             "enabled": bool(cfg.get("enabled", True)),
             "relayer": None, "relayer_key_present": False,
             "build": cfg.get("build", "GATE-2")}
    try:
        _priv, addr = load_relayer(cfg, base_dir)
        state["relayer"] = addr
        state["relayer_key_present"] = True
    except Exception:
        pass
    return state


def _fail(record, code, predicate, repair, **extra):
    record.update({"status": "FAIL_CLOSED", "failure_code": code,
                   "failed_predicate": predicate,
                   "required_evidence_or_repair": repair,
                   "owning_goal": OWNING_GOAL, **extra})
    return record


def attempt_settlement(payment, cfg, base_dir):
    """Submit a verified authorization for on-chain settlement via the
    gas-only relayer. Returns the settlement record dict that rides the
    crossing's receipt pair. Never raises; never changes the crossing's
    disposition (see module docstring for the mode (a) mapping).

    BUILD-Q-45 hardening (2026-11-17): the body below historically
    could raise despite this contract (an unguarded int()/index on an
    RPC result). The wrapper keeps the contract: any unexpected
    exception becomes a SETTLEMENT_INTERNAL record. Every raise site
    is before broadcast, except a malformed-receipt read after a
    successful broadcast -- in that case the record cannot name the
    outcome, but the crossing pair still issues and the operator
    route can reconcile from the journal/on-chain state."""
    record = {"build": cfg.get("build", "GATE-2"),
              "mode": cfg.get("mode", "self-relayer"),
              "attempted": False, "status": "NOT_ATTEMPTED",
              "asset": payment.get("asset"),
              "payTo": payment.get("payTo"),
              "value_micro_usdc": payment.get("value_micro_usdc"),
              "nonce": payment.get("nonce")}
    try:
        return _attempt_settlement_body(payment, cfg, base_dir, record)
    except Exception as e:
        return _fail(record, "SETTLEMENT_INTERNAL",
                     "the settlement leg returns a settlement record for every verified authorization",
                     "endpoint repair of the settlement leg; if a tx hash is recorded the on-chain state governs, otherwise the authorization remains submittable",
                     error=f"{type(e).__name__}: {e}"[:200])


def _attempt_settlement_body(payment, cfg, base_dir, record):
    record = {"build": cfg.get("build", "GATE-2"),
              "mode": cfg.get("mode", "self-relayer"),
              "attempted": False, "status": "NOT_ATTEMPTED",
              "asset": payment.get("asset"),
              "payTo": payment.get("payTo"),
              "value_micro_usdc": payment.get("value_micro_usdc"),
              "nonce": payment.get("nonce")}
    if not cfg.get("enabled", True):
        record["status"] = "DISABLED"
        record["note"] = "settlement submission disabled by configuration"
        return record
    try:
        priv, relayer = load_relayer(cfg, base_dir)
    except Exception as e:
        return _fail(record, "SETTLEMENT_RELAYER_KEY_MISSING",
                     "the gas-only relayer key file is present and readable on the node",
                     "run relayer_setup.py on the endpoint node to generate the relayer key, then fund its address with dust ETH on Base",
                     error=f"{type(e).__name__}: {e}"[:200])
    record["relayer"] = relayer
    record["attempted"] = True
    try:
        calldata = build_transfer_calldata(payment)
    except Exception as e:
        return _fail(record, "SETTLEMENT_BROADCAST_FAILED",
                     "the verified authorization encodes as transferWithAuthorization calldata",
                     "re-present the authorization; if the failure persists the payment evidence is inconsistent with its verified signature",
                     error=f"{type(e).__name__}: {e}"[:200])
    rpc = Rpc([cfg.get("rpc_primary", "https://mainnet.base.org"),
               cfg.get("rpc_fallback", "https://base-rpc.publicnode.com")])
    asset = payment["asset"]
    try:
        balance = int(rpc.call("eth_getBalance", [relayer, "latest"]), 16)
    except RpcError as e:
        return _fail(record, "SETTLEMENT_RPC_UNREACHABLE",
                     "a configured Base RPC answers for the settlement leg",
                     "retry the crossing later; if the failure persists, check the node's egress to the configured RPCs",
                     error=str(e))
    record["rpc"] = rpc.answered_by
    record["relayer_balance_wei"] = balance
    if balance == 0:
        return _fail(record, "SETTLEMENT_RELAYER_UNFUNDED",
                     "the relayer holds enough Base ETH to pay settlement gas",
                     f"fund the relayer address {relayer} with dust ETH on Base (about $2 covers thousands of settlements at prevailing Base fees); the verified authorization remains submittable -- re-present it or replay the settlement from the receipted pair")
    try:
        estimate = int(rpc.call("eth_estimateGas",
                                [{"from": relayer, "to": asset,
                                  "data": "0x" + calldata.hex()}]), 16)
    except RpcError as e:
        return _fail(record, "SETTLEMENT_SIMULATION_REVERTED",
                     "the transferWithAuthorization call simulates successfully against the live USDC contract",
                     "the authorization's on-chain predicates failed (nonce already used on-chain, window closed on-chain, or payer balance below the authorized value); a fresh funded authorization is required",
                     error=str(e))
    gas_limit = int(estimate * 1.3) + 10000
    try:
        # Fee read via eth_feeHistory: a compact response. The full
        # block read is several KB and the node's bare egress proxy
        # truncates responses of that size (IncompleteRead /
        # RemoteDisconnected, observed 2026-11-17 in the PAIR-000017
        # resubmission attempt); it is kept only as a fallback for
        # routes that carry it. baseFeePerGas[-1] is the pending
        # block's base fee -- the right basis for maxFeePerGas.
        try:
            fee_hist = rpc.call("eth_feeHistory", ["0x1", "latest", []])
            base_fee = int(fee_hist["baseFeePerGas"][-1], 16)
        except RpcError:
            block = rpc.call("eth_getBlockByNumber", ["latest", False])
            base_fee = int(block["baseFeePerGas"], 16)
        try:
            priority = int(rpc.call("eth_maxPriorityFeePerGas", []), 16)
        except RpcError:
            priority = 100000
    except RpcError as e:
        return _fail(record, "SETTLEMENT_RPC_UNREACHABLE",
                     "a configured Base RPC answers for the settlement leg",
                     "retry the crossing later",
                     error=str(e))
    max_fee = 2 * base_fee + priority
    cost = gas_limit * max_fee
    record["gas"] = {"estimate": estimate, "limit": gas_limit,
                     "max_fee_per_gas_wei": max_fee,
                     "max_cost_wei": cost}
    if balance < cost:
        return _fail(record, "SETTLEMENT_RELAYER_UNFUNDED",
                     "the relayer holds enough Base ETH to pay settlement gas",
                     f"fund the relayer address {relayer} with dust ETH on Base; the verified authorization remains submittable",
                     relayer_balance_wei=balance, max_cost_wei=cost)
    try:
        tx_nonce = int(rpc.call("eth_getTransactionCount",
                                [relayer, "pending"]), 16)
    except RpcError as e:
        return _fail(record, "SETTLEMENT_RPC_UNREACHABLE",
                     "a configured Base RPC answers for the settlement leg",
                     "retry the crossing later",
                     error=str(e))
    fields = [CHAIN_ID, tx_nonce, priority, max_fee, gas_limit,
              bytes.fromhex(asset[2:]), 0, calldata, []]
    sighash = keccak256(b"\x02" + rlp_encode(fields))
    r, s, recid = sign_digest(priv, sighash)
    raw = b"\x02" + rlp_encode(fields + [recid, r, s])
    # The transaction hash is locally computable from the signed raw
    # transaction (BUILD-Q-45 repair, 2026-11-17): a broadcast error
    # is ambiguous -- the node may have accepted the transaction
    # before the connection failed (the PAIR-000019 history) -- so on
    # error the receipt for the local hash is checked before the
    # attempt is recorded as failed.
    local_tx_hash = "0x" + keccak256(raw).hex()
    try:
        # Failover ACROSS URLs is required here (cure, 2026-11-18):
        # this call previously passed allow_failover=False, pinning
        # the broadcast to the primary RPC only -- the route that
        # refuses this node's service-form transport (HTTP 403 via
        # the bare proxy) -- while every read failed over to the
        # fallback and succeeded. That asymmetry is the exact root
        # cause of PAIR-000038's SETTLEMENT_BROADCAST_FAILED record,
        # whose error lists primary-only attempts. Cross-URL failover
        # is safe for a send: the identical signed bytes hash to the
        # same transaction on every route, and if an earlier route
        # accepted it before its response was lost, the later route's
        # "already known" error lands in the handler below, which
        # resolves the outcome against the locally computed hash.
        tx_hash = rpc.call("eth_sendRawTransaction",
                           ["0x" + raw.hex()])
    except RpcError as e:
        receipt = None
        try:
            receipt = rpc.call("eth_getTransactionReceipt",
                               [local_tx_hash])
        except Exception:
            receipt = None
        if receipt and receipt.get("status") == "0x1":
            record.update({"attempted": True, "status": "SETTLED",
                           "tx_hash": local_tx_hash,
                           "block_number": int(
                               receipt.get("blockNumber") or "0x0", 16),
                           "note": "broadcast raised, but the transaction is confirmed on-chain under its locally computed hash"})
            return record
        if receipt and receipt.get("status") == "0x0":
            return _fail(record, "SETTLEMENT_REVERTED_ONCHAIN",
                         "the settlement transaction executes successfully on-chain",
                         "the authorization's on-chain nonce state governs; do not resubmit blindly",
                         tx_hash=local_tx_hash,
                         error=f"broadcast raised ({e}); receipt status 0x0")
        return _fail(record, "SETTLEMENT_BROADCAST_FAILED",
                     "the signed settlement transaction is accepted by the Base network",
                     "check the recorded tx_hash on-chain before any resubmission: the broadcast error is ambiguous and the transaction may have landed",
                     tx_hash=local_tx_hash,
                     error=str(e))
    record["tx_hash"] = tx_hash
    record["status"] = "SUBMITTED"
    record["note"] = "broadcast accepted; confirmation pending when this record was written"
    for _ in range(5):
        time.sleep(2)
        try:
            receipt = rpc.call("eth_getTransactionReceipt", [tx_hash])
        except RpcError:
            break
        if receipt:
            if receipt.get("status") == "0x1":
                record["status"] = "SETTLED"
                record["block_number"] = int(
                    receipt.get("blockNumber") or "0x0", 16)
                record.pop("note", None)
            else:
                return _fail(record, "SETTLEMENT_REVERTED_ONCHAIN",
                             "the settlement transaction executes successfully on-chain",
                             "the authorization remains unconsumed (a revert does not consume the EIP-3009 nonce); diagnose the revert and re-submit",
                             tx_hash=tx_hash)
            break
    return record


def simulate(payment, cfg, base_dir):
    """Read-only broadcast-path exercise (acceptance use): build the
    exact calldata the broadcast leg would send and dispatch it to the
    live USDC contract via eth_call. Returns what the contract said --
    success, or the revert -- without moving anything."""
    calldata = build_transfer_calldata(payment)
    rpc = Rpc([cfg.get("rpc_primary", "https://mainnet.base.org"),
               cfg.get("rpc_fallback", "https://base-rpc.publicnode.com")])
    out = {"selector": "0x" + TRANSFER_SELECTOR.hex(),
           "calldata_bytes": len(calldata), "dispatched": False}
    try:
        _priv, sender = load_relayer(cfg, base_dir)
    except Exception:
        sender = payment["from"]
    out["from"] = sender
    try:
        result = rpc.call("eth_call",
                          [{"from": sender, "to": payment["asset"],
                            "data": "0x" + calldata.hex()}, "latest"])
        out.update({"dispatched": True, "outcome": "success",
                    "result": result, "rpc": rpc.answered_by})
    except RpcError as e:
        out.update({"dispatched": True, "outcome": "reverted",
                    "error": str(e), "rpc": rpc.answered_by})
    return out
